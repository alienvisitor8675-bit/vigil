"""The task contract: the only thing that crosses the vigild-executor boundary.

`schemas/*.json` are generated from these models
(`uv run python -m vigild.contract.export`); a test fails if they drift.
"""

from __future__ import annotations

import re
from enum import StrEnum
from typing import Annotated, Any, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from vigild.provenance import Provenance

Score = Annotated[int, Field(ge=1, le=5)]
KEY_REF = re.compile(r"^[A-Z][A-Z0-9_]{1,63}$")


class Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


class BackendKind(StrEnum):
    ANTHROPIC = "anthropic"
    OPENAI_COMPATIBLE = "openai_compatible"
    OPENROUTER = "openrouter"


class Backend(Strict):
    """A model backend. `key_ref` names a variable in ~/.config/vigil/env."""

    kind: BackendKind
    base_url: str
    model: str | None = None
    key_ref: str

    @field_validator("key_ref")
    @classmethod
    def _name_not_value(cls, v: str) -> str:
        if not KEY_REF.match(v):
            raise ValueError("key_ref must be an env variable NAME, never a key value")
        return v


# The verification ladder (owner decisions 2026-10-22). Level 0: example tests
# that fail first. Level 1 (phase 2): properties derived from the criteria.
# Level 3 (after phase 2): models of state machines. 2, 4, 5: later options.
BUILT_VERIFY_LEVELS = frozenset({0})


class Verify(Strict):
    level: int = Field(default=0, ge=0, le=5)
    method: str | None = None


class Spec(Strict):
    goal: str
    test_cmd: str | None = None
    must_fail_first: bool = True
    files_in_scope: list[str] = Field(default_factory=list)
    done_when: str | None = None
    out_of_scope: list[str] = Field(default_factory=list)
    verify: Verify = Field(default_factory=Verify)


class Limits(Strict):
    max_turns: int = Field(default=60, ge=1)
    max_minutes: int = Field(default=40, ge=1)
    max_cost_usd: float = Field(default=1.0, gt=0)


class Size(StrEnum):
    XS = "XS"
    S = "S"
    M = "M"
    L = "L"


class Shape(StrEnum):
    """The kind of change, for the review ladder (phase 2). `deps` changes
    only manifests and lockfiles, runs no model, starts at rung 1 and always
    needs the owner's review (round 3)."""

    DOCS = "docs"
    TESTS = "tests"
    FEATURE = "feature"
    FIX = "fix"
    REFACTOR = "refactor"
    DEPS = "deps"


class DepRequest(Strict):
    """A dependency a worker needs and the repo's dev image doesn't have."""

    ecosystem: Literal["npm", "pypi"]
    package: str = Field(min_length=1, max_length=214)
    version: str = Field(min_length=1, max_length=64)
    why: str = ""


class Source(StrEnum):
    HUMAN = "human"
    SELF = "self"  # generated by the fleet (an audit or a coord)


class Task(Strict):
    task_id: str
    repo: str
    base: str = "main"
    branch: str | None = None
    tier: str | None = None
    tier_reason: str | None = None
    backend: Backend | str | None = None  # a preset name or a custom object
    why: str
    value: Score
    risk: Score
    spec: Spec
    limits: Limits = Field(default_factory=Limits)
    depends_on: list[str] = Field(default_factory=list)
    attempt: int = Field(default=1, ge=1)
    job_id: str | None = None
    source: Source = Source.HUMAN
    labels: list[str] = Field(default_factory=list)
    size: Size | None = None
    review_rounds: int = 0
    has_existing_tests: bool | None = None
    shape: Shape | None = None
    # A deps task names the task it unblocks; a blocked task names its deps job.
    parent_task: str | None = None
    blocked_on: str | None = None


class TestOutcome(StrEnum):
    FAIL = "fail"
    PASS = "pass"  # noqa: S105 (a test outcome, not a password)
    UNKNOWN = "unknown"


class Usage(Strict):
    model: str
    tokens_in: int = 0
    tokens_out: int = 0
    tokens_cache_read: int = 0
    tokens_cache_write: int = 0
    cost_usd: float = 0
    gpu_seconds: float | None = None
    energy_j: float | None = None


class ResultStatus(StrEnum):
    PR_OPEN = "pr_open"
    FAILED = "failed"
    ESCALATE = "escalate"
    TIMEOUT = "timeout"


class Result(Strict):
    task_id: str
    status: ResultStatus
    branch: str
    pr_url: str | None = None
    test_before: TestOutcome
    test_after: TestOutcome
    files_changed: list[str]
    summary: str
    usage: Usage
    trace_id: str | None = None
    provenance: Provenance


class EventType(StrEnum):
    MODEL_REQUEST = "model_request"
    TOOL_CALL = "tool_call"
    TOOL_RESULT = "tool_result"
    DECISION = "decision"
    STATE = "state"


class Event(Strict):
    session_id: str | None = None
    task_id: str | None = None
    job_id: str | None = None
    ts: str | None = None
    type: EventType
    data: dict[str, Any]
    provenance: Provenance


class SelfCheck(Strict):
    """The five questions every worker answers before returning."""

    test_failed_first: bool
    outside_scope: list[str]  # must be empty; anything here is explained in not_done
    not_done: str
    reviewer_would_flag: str
    could_delete: str


class WorkerReport(Strict):
    task_id: str
    job_id: str
    # Ignored: vigild overwrites both with what its verifier saw (round 2).
    test_before: TestOutcome = TestOutcome.UNKNOWN
    test_after: TestOutcome = TestOutcome.UNKNOWN
    files_changed: list[str]
    summary: str
    self_check: SelfCheck
    open_questions: list[str] = Field(default_factory=list)
    # Dependencies the work needs that the dev image lacks; the task blocks
    # on a deps job instead of being judged (round 3).
    needs_deps: list[DepRequest] = Field(default_factory=list)
    provenance: Provenance


class WorkerContract(Strict):
    """One worker's contract inside plan.md; vigild routes it into a Task."""

    task_id: str
    goal: str
    why: str
    value: Score
    risk: Score
    size: Size
    test_cmd: str = Field(min_length=1, pattern=r"\S")  # never blank (review round 2, N2)
    done_when: str
    files_in_scope: list[str] = Field(min_length=1)
    out_of_scope: list[str] = Field(default_factory=list)
    must_fail_first: bool = True
    depends_on: list[str] = Field(default_factory=list)
    labels: list[str] = Field(default_factory=list)
    max_cost_usd: float | None = Field(default=None, gt=0)
    verify_level: int = Field(default=0, ge=0, le=5)


class CriterionVerify(Strict):
    """How high one acceptance criterion's verification reaches, and why not higher."""

    criterion: str
    level: int = Field(ge=0, le=5)
    why_not_higher: str | None = None

    @model_validator(mode="after")
    def _say_why(self) -> CriterionVerify:
        if self.level == 0 and not (self.why_not_higher or "").strip():
            raise ValueError(f"{self.criterion}: why_not_higher is required at level 0")
        return self


class Plan(Strict):
    workers: list[WorkerContract]
    verify: list[CriterionVerify] = Field(min_length=1)


Verdict = Literal["clean", "changes"]
